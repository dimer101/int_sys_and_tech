def fit_minmax(matrix):
    n_feat = len(matrix[0])
    
    mins = []
    for j in range (n_feat):
        column_values = []
        for row in matrix:
            column_values.append(row[j])
        mins.append(min(column_values))
        
    maxs = []
    for j in range (n_feat):
        column_values = []
        for row in matrix:
            column_values.append(row[j])
        maxs.append(max(column_values))
        
    return mins, maxs


def scale(vector, mins, maxs):
    out = []
    
    for i in range (len(vector)):
        x = vector[i]
        lowest = mins[i]
        highest = maxs[i]
        difference = highest - lowest
        out.append(0.0 if difference == 0 else (x - lowest) / difference)
        
    return out


def euclidean(a, b):
    
    return math.sqrt(sum((a[i] - b[i]) ** 2 for i in range(len(a))))


def count_votes(neighbors):
    votes = {}
    for pair in neighbors:
        brand = pair[1]
        if brand in votes:
            votes[brand] += 1
        else:
            votes[brand] = 1
            
    return votes



def predict_knn(new_vector, features, brand, k=4):
    distances_and_brand = []
    for i in range(len(features)):
        distance = euclidean(new_vector, features[i])
        distances_and_brand.append((distance, brand[i]))
        
    distances_and_brand.sort()
    
    neighbors = []
    for i in range(k):
        neighbors.append(distances_and_brand[i])
        
    while True:
        votes = count_votes(neighbors)
        if len(votes) == 1 or len(neighbors) == 1:
            break
        
        labels = list(votes.keys())
        if votes[labels[0]] != votes[labels[1]]:
            break
        
        print(f"  ничья {votes} => убираем дальнего (расстояние = {neighbors[-1][0]:.3f}, {neighbors[-1][1]})")
        
        neighbors.pop()
        

    if votes.get("Айфон", 0) >= votes.get("Андроид", 0):
        winner = "Айфон"
    else:
        winner = "Андроид"
        
    confidence = votes[winner] / len(neighbors) * 100
    return winner, confidence, neighbors



