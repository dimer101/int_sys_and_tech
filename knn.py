def sphere_category(raw):
    s = raw.strip().lower()
    if "студент" in s:
        return "Студент"
    if any(k in s for k in ("it", "ит", "програм", "разраб", "инжен", "тех")):
        return "IT"
    if "дизайн" in s or "медиа" in s:
        return "Дизайн и медиа"
    if any(k in s for k in ("продаж", "бизнес", "менедж", "предпри")):
        return "Бизнес"
    return "Другое"


